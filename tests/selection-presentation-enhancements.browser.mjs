async page => {
  await page.goto('http://127.0.0.1:8791');
  await page.evaluate(() => { localStorage.removeItem('supjx.smartbrowser.collection.view'); localStorage.removeItem('supjx.smartbrowser.collection.view.multiple-layout'); localStorage.removeItem('supjx.smartbrowser.collection.view.single-layout'); });
  await page.goto('http://127.0.0.1:8791?fieldFixture=1&usageMode=editable&presentationFixture=1');
  const article = page.locator('.sb-selection-field').nth(2);
  await article.getByLabel('Displayed name', { exact: true }).fill('Temporary name');
  if ((await article.locator('.resource-info-panel > h3').innerText()).trim() !== 'Temporary name') throw Error('Displayed title not effective');
  await article.getByLabel('Visual presentation', { exact: true }).selectOption('icon');
  await article.getByLabel('Icon', { exact: true }).fill('fas fa-book');
  await article.locator('.sb-collection-count-toggle').click();
  await article.getByRole('button', { name: 'Grid', exact: true }).click();
  await article.locator('.resource-browser-item').first().waitFor();
  if (await article.locator('.resource-browser-item .resource-visual-image').count()) throw Error('Icon mode includes thumbnail');
  await article.getByLabel('Visual presentation', { exact: true }).selectOption('both');
  await article.locator('.resource-browser-item .resource-visual-image').waitFor();
  await article.getByRole('button', { name: 'Replace', exact: true }).click();
  const picker = page.frameLocator('dialog.smartbrowser-picker iframe');
  await picker.getByLabel('Displayed name', { exact: true }).waitFor();
  if (await picker.getByLabel('Displayed name', { exact: true }).inputValue() !== 'Temporary name') throw Error('Displayed name lost on reopen');
  await picker.locator('.resource-actions').getByRole('button', { name: 'Select', exact: true }).click();
  await page.locator('dialog.smartbrowser-picker').waitFor({ state: 'detached' });
  const multi = page.locator('.sb-selection-field').nth(3);
  await multi.locator('.sb-collection-count-toggle').click();
  await multi.getByRole('button', { name: 'List', exact: true }).click();
  await multi.evaluate(async root => {
    const items = JSON.parse(root.querySelector('[data-sb-value]').value).items;
    items.forEach(item => { item.usage['ext.smartcrop.crop'] = { identity: item.selection.id }; });
    await SmartBrowser.mountSelectionField(root).setItems(items);
  });
  const before = await multi.locator('[data-sb-value]').inputValue();
  await multi.locator('thead .resource-column-title button').click();
  if (await multi.locator('.resource-ordering-moves').count()) throw Error('Ordering arrows remain under view sorting');
  if (await multi.locator('[data-sb-value]').inputValue() !== before) throw Error('View sort mutated stored order');
  const titles = await multi.locator('tbody .resource-title-cell').allTextContents();
  if (titles[0].trim() !== 'First image') throw Error('View sort not effective');
  await multi.getByRole('button', { name: 'Columns', exact: true }).click();
  await multi.locator('.resource-column-menu').getByLabel('Created', { exact: true }).check();
  await multi.locator('.resource-column-menu').getByLabel('ID', { exact: true }).check();
  await page.keyboard.press('Escape');
  if (!await multi.locator('thead .resource-column-created').count()) throw Error('Date column unavailable');
  await multi.locator('thead .resource-ordering-sort').click();
  await multi.getByRole('button', { name: 'Sort selection order', exact: true }).click();
  const dialog = multi.locator('dialog.resource-batch-dialog[open]');
  await dialog.getByLabel('Sort', { exact: true }).selectOption('title');
  await dialog.getByRole('button', { name: 'Apply', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const stored = JSON.parse(await multi.locator('[data-sb-value]').inputValue());
  if (stored.items[0].selection.id !== 'local-images:/a.png') throw Error('Collection sort did not persist');
  for (const entry of stored.items) if (entry.usage['ext.smartcrop.crop'].identity !== entry.selection.id) throw Error('Metadata detached from identity');
  await page.reload();
  await multi.getByRole('button', { name: 'Columns', exact: true }).waitFor();
  if (!await multi.locator('thead .resource-column-created').count()) throw Error('Column preference lost');
  return 'Article name/modes, reopen, view sorting, common columns, whole-collection ordering and extension metadata passed.';
}
