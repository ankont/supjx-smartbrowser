async page => {
  const check = (value, message) => { if (!value) throw Error(message); };
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('http://127.0.0.1:8791');
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await page.goto('http://127.0.0.1:8791?view=browser');
  const toolbar = page.locator('.resource-toolbar').first();
  await toolbar.getByRole('button', { name: 'Grid', exact: true }).click();
  const initialHeight = (await toolbar.boundingBox()).height;
  await toolbar.getByRole('button', { name: 'Search', exact: true }).click();
  const search = toolbar.getByRole('searchbox', { name: 'Search', exact: true });
  await search.fill('First');
  check(await search.evaluate(el => el.closest('[popover]').matches(':popover-open')), 'Search is not a popup');
  check((await toolbar.boundingBox()).height === initialHeight, 'Search moved the browsing content');
  await page.keyboard.press('Escape');
  check(!await search.isVisible(), 'Escape did not dismiss Search');
  await toolbar.locator('.resource-toolbar-popup > button[aria-label="Search"]').click();
  await search.waitFor({ state: 'visible' });
  await toolbar.locator('.resource-toolbar-popup > button[aria-label="Search"]').click();
  await search.waitFor({ state: 'hidden' });
  const browserSort = toolbar.getByRole('button', { name: 'Sort by', exact: true });
  const browserSortBefore = await browserSort.boundingBox();
  await browserSort.click();
  const sort = toolbar.getByRole('combobox', { name: 'Sort by', exact: true });
  await sort.selectOption('title');
  check(await sort.evaluate(el => el.closest('.resource-toolbar-popup').classList.contains('is-inline')), 'Wide sort should be inline');
  check(Math.abs((await browserSort.boundingBox()).x - browserSortBefore.x) < 1, 'Browser sort trigger moved');
  check((await toolbar.locator('.resource-sort-menu').boundingBox()).x < browserSortBefore.x, 'Right-aligned Browser sort must expand left');
  check(await browserSort.locator('.fa-signal').count(), 'Sort icon is not Signal');
  check((await toolbar.boundingBox()).height === initialHeight, 'Sort added a toolbar row');
  await toolbar.getByRole('button', { name: 'Sort direction', exact: true }).click();
  await toolbar.getByRole('button', { name: 'List', exact: true }).click();
  check(!await toolbar.getByRole('button', { name: 'Sort by', exact: true }).count(), 'List exposes grid sorting control');
  await toolbar.getByRole('button', { name: 'Columns', exact: true }).click();
  await toolbar.locator('.resource-column-menu').waitFor({ state: 'visible' });
  check(await toolbar.locator('.resource-column-menu input[type="checkbox"]').count() > 0, 'Column choices are missing');
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await toolbar.getByRole('button', { name: 'Grid', exact: true }).click();
  await toolbar.getByRole('button', { name: 'Sort by', exact: true }).click();
  check(await sort.evaluate(el => el.closest('[popover]').matches(':popover-open')), 'Narrow sort should use a popup');
  const sortBox = await toolbar.locator('.resource-sort-menu').boundingBox();
  check(sortBox.x >= 0 && sortBox.x + sortBox.width <= 390, 'Sort popup overflows viewport');
  await page.screenshot({ path: 'build/toolbar-mobile.png' });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('http://127.0.0.1:8791?fieldFixture=1');
  const multiple = page.locator('.sb-selection-field').nth(3);
  await multiple.locator('.sb-collection-count-toggle').click();
  const commands = await multiple.locator('.sb-collection-toolbar .resource-view-controls > button, .sb-collection-toolbar .resource-ordering-moves button').evaluateAll(buttons => buttons.map(button => button.getAttribute('aria-label') || button.title));
  const replaceIndex = commands.indexOf('Replace');
  check(commands[replaceIndex + 1] === 'COM_SMARTBROWSER_MOVE_UP' && commands[replaceIndex + 2] === 'COM_SMARTBROWSER_MOVE_DOWN' && commands[replaceIndex + 3] === 'Sort selection order', 'Ordering actions must follow Replace');
  await multiple.getByRole('button', { name: 'List', exact: true }).click();
  check(!await multiple.getByRole('button', { name: 'Search', exact: true }).count(), 'Selection does not need Search');
  check(!await multiple.getByRole('button', { name: 'Sort by', exact: true }).count(), 'Selection list exposes grid sorting');
  const height = (await multiple.locator('.sb-collection-toolbar').boundingBox()).height;
  await multiple.getByRole('button', { name: 'Columns', exact: true }).click();
  await multiple.locator('.resource-column-menu').getByLabel('Created', { exact: true }).check();
  check(await multiple.locator('thead .resource-column-created').count(), 'Shared column popup did not toggle column');
  check((await multiple.locator('.sb-collection-toolbar').boundingBox()).height === height, 'Columns added a toolbar row');
  await page.keyboard.press('Escape');
  await multiple.getByRole('button', { name: 'Grid', exact: true }).click();
  check(!await multiple.getByRole('button', { name: 'Columns', exact: true }).count(), 'Grid exposes Columns');
  const selectionSort = multiple.getByRole('button', { name: 'Sort by', exact: true });
  await selectionSort.scrollIntoViewIfNeeded();
  const selectionSortBefore = await selectionSort.boundingBox();
  await selectionSort.click();
  check(Math.abs((await selectionSort.boundingBox()).x - selectionSortBefore.x) < 1, 'Selection sort trigger moved');
  if (await selectionSort.evaluate(button => button.parentElement.classList.contains('is-inline'))) {
    check((await multiple.locator('.resource-sort-menu').boundingBox()).x >= selectionSortBefore.x + selectionSortBefore.width, 'Left-aligned selection sort must expand right');
  }
  await multiple.locator('.sb-collection-toolbar').screenshot({ path: 'build/selection-sort-inline.png' });
  await multiple.getByRole('combobox', { name: 'Sort by', exact: true }).selectOption('title');
  check(!await multiple.locator('.resource-ordering-moves').count(), 'View sorting must hide stored ordering arrows');
  await page.keyboard.press('Escape');
  await page.evaluate(async () => {
    const root = document.querySelectorAll('.sb-selection-field')[3];
    const config = JSON.parse(root.dataset.sbField);
    const target = document.createElement('div'); target.id = 'unordered-selection'; document.body.append(target);
    window.unordered = SmartBrowser.mountCollection(target, { ...config, selectedResources: true, referenceItems: true, allowOrdering: false,
      items: JSON.parse(root.querySelector('[data-sb-value]').value).items, viewPreferenceKey: 'test.no-order', translate: key => Joomla.Text._(key, key) });
    await unordered.ready;
  });
  const unordered = page.locator('#unordered-selection');
  await unordered.locator('.sb-collection-count-toggle').click();
  await unordered.getByRole('button', { name: 'Grid', exact: true }).click();
  await unordered.getByRole('button', { name: 'Sort by', exact: true }).click();
  check(await unordered.getByRole('combobox', { name: 'Sort by', exact: true }).inputValue() === 'title', 'Unordered selection did not default to Name');
  check(!await unordered.locator('option[value="collectionOrder"]').count(), 'Ordering option remains');
  check(!await unordered.getByRole('button', { name: 'Sort selection order', exact: true }).count(), 'Ordering action remains');
  await page.keyboard.press('Escape');
  await unordered.getByRole('button', { name: 'List', exact: true }).click();
  check(!await unordered.locator('.resource-ordering-sort, .resource-ordering-moves').count(), 'Ordering controls remain in list');
  await page.screenshot({ path: 'build/selection-toolbar-columns.png' });
  return 'Shared Columns popup, Grid-only sorting, no selection search, inline/popup Browser sorting, search popup, stable toolbar geometry, mobile bounds and allowOrdering:false passed.';
}
